`timescale 1ns / 1ps

module stopwatch_tb;

//====================================================
// Testbench Signals
//====================================================

reg clk;
reg rst;
reg start;
reg pause;

wire [5:0] seconds;
wire [5:0] minutes;

//====================================================
// DUT (Device Under Test)
//====================================================

stopwatch #(
    .CLOCK_FREQ(10)
)
dut
(
    .clk(clk),
    .rst(rst),
    .start(start),
    .pause(pause),
    .seconds(seconds),
    .minutes(minutes)
);

//====================================================
// Clock Generation
// 10 ns Clock Period
//====================================================

always #5 clk = ~clk;

//====================================================
// Test Sequence
//====================================================

initial
begin

    //----------------------------------------
    // Initialize Signals
    //----------------------------------------

    clk   = 0;
    rst   = 1;
    start = 0;
    pause = 0;

    //----------------------------------------
    // Apply Reset
    //----------------------------------------

    #20;
    rst = 0;

    //----------------------------------------
    // Start Stopwatch
    //----------------------------------------

    #20;
    start = 1;

    #10;
    start = 0;

    //----------------------------------------
    // Run for some time
    //----------------------------------------

    #700;

    //----------------------------------------
    // Pause
    //----------------------------------------

    pause = 1;

    #10;
    pause = 0;

    //----------------------------------------
    // Wait while paused
    //----------------------------------------

    #200;

    //----------------------------------------
    // Resume
    //----------------------------------------

    start = 1;

    #10;
    start = 0;

    //----------------------------------------
    // Run Again
    //----------------------------------------

    #700;

    //----------------------------------------
    // Reset
    //----------------------------------------

    rst = 1;

    #20;

    rst = 0;

    //----------------------------------------
    // Stop Simulation
    //----------------------------------------

    #100;

    $stop;

end

endmodule